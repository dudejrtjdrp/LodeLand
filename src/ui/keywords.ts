/** 화면 표기 → 사전 항목 (별칭 포함, 대소문자 무시) */
const ALIAS_INDEX: Map<string, KeywordEntry> = (() => {
	const index = new Map<string, KeywordEntry>();
	for (const [key, entry] of Object.entries(KEYWORDS)) {
		index.set(key.toLowerCase(), entry);
		for (const alias of entry.aliases ?? []) {
			index.set(alias.toLowerCase(), entry);
		}
	}
	return index;
})();

/** 정확한 표기(또는 별칭)로 사전 항목을 찾는다. */
export function findKeyword(term: string | null | undefined): KeywordEntry | null {
	if (!term) {
		return null;
	}
	return ALIAS_INDEX.get(term.trim().toLowerCase()) ?? null;
}

/**
 * 임의의 문장에서 사전에 있는 용어를 최대 2개까지 찾아 각주를 만든다.
 * 카드·상품 설명 툴팁 아래에 "용어" 블록으로 붙인다.
 */
export function keywordNotesIn(text: string | null | undefined, limit = 2): KeywordEntry[] {
	if (!text) {
		return [];
	}
	const found: KeywordEntry[] = [];
	const seen = new Set<KeywordEntry>();
	for (const [alias, entry] of ALIAS_INDEX) {
		if (found.length >= limit) {
			break;
		}
		// 1글자 별칭은 오탐이 많다 — 2글자 이상만 본문 검색에 쓴다
		if (alias.length < 2 || seen.has(entry)) {
			continue;
		}
		if (text.toLowerCase().includes(alias)) {
			seen.add(entry);
			found.push(entry);
		}
	}
	return found;
}

/** 사전 항목을 툴팁 본문 한 덩어리로 이어 붙인다. */
export function keywordFooter(text: string | null | undefined, limit = 2): string {
	const notes = keywordNotesIn(text, limit);
	if (notes.length === 0) {
		return '';
	}
	return notes.map((entry) => `— ${entry.title}: ${entry.body.split('\n')[0]}`).join('\n');
}
